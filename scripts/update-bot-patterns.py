#!/usr/bin/env python3
"""Regenerate src/Service/BotDetection/BotUserAgentPatterns.php.

Usage: python3 scripts/update-bot-patterns.py path/to/crawler-user-agents [commit]

The source is a checkout of https://github.com/monperrus/crawler-user-agents
(MIT License; its notice is kept in src/Service/BotDetection/LICENSE-crawler-user-agents).
Entries tagged http-library (curl, python-requests and similar) are left out:
those clients are how websites send server-side events, and they cannot run
the browser tracker, so treating them as bots would only drop legitimate
server-side collection.
"""

import json
import pathlib
import subprocess
import sys

EXCLUDED_TAGS = {"http-library"}
OUTPUT = pathlib.Path(__file__).resolve().parent.parent / "src/Service/BotDetection/BotUserAgentPatterns.php"


def php_string(value: str) -> str:
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def main() -> int:
    if len(sys.argv) < 2:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    source = pathlib.Path(sys.argv[1])
    entries = json.loads((source / "crawler-user-agents.json").read_text(encoding="utf-8"))
    commit = sys.argv[2] if len(sys.argv) > 2 else subprocess.run(
        ["git", "-C", str(source), "rev-parse", "HEAD"], check=True, capture_output=True, text=True,
    ).stdout.strip()

    patterns = []
    for entry in entries:
        if EXCLUDED_TAGS & set(entry.get("tags") or []):
            continue
        pattern = entry["pattern"]
        if "\n" in pattern or pattern in patterns:
            continue
        patterns.append(pattern)

    lines = [
        "<?php",
        "",
        "declare(strict_types=1);",
        "",
        "namespace App\\Service\\BotDetection;",
        "",
        "/**",
        " * User-Agent patterns of crawlers, monitors and automation tools, generated by",
        " * scripts/update-bot-patterns.py from monperrus/crawler-user-agents (MIT License;",
        " * see LICENSE-crawler-user-agents in this directory). Entries tagged http-library",
        " * are left out. Do not edit by hand; regenerate from a newer upstream commit.",
        " */",
        "final class BotUserAgentPatterns",
        "{",
        "    public const SOURCE = 'https://github.com/monperrus/crawler-user-agents';",
        "    public const SOURCE_COMMIT = " + php_string(commit) + ";",
        "",
        "    /** Regular expressions as published upstream, matched case-sensitively. */",
        "    public const PATTERNS = [",
    ]
    lines += ["        " + php_string(pattern) + "," for pattern in patterns]
    lines += ["    ];", "}", ""]
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {len(patterns)} patterns from {len(entries)} entries ({commit}) to {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
